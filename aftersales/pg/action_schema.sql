-- PostgreSQL port of aftersales/action_schema.sql (V2 Stage 6 action schema).
--
-- Applied after aftersales/pg/schema.sql. Same tables, keys, CHECK / UNIQUE /
-- foreign-key constraints and partial unique indexes; only the dialect differs:
--   x IS 'APPROVE'          -> x IS NOT DISTINCT FROM 'APPROVE'
--       A NULL decision must FAIL these checks, as it does with SQLite's IS.
--       A plain `=` would be NULL for a NULL decision and a CHECK passes on
--       NULL: that is the Stage 6.2 schema bug `IS` fixed, so `=` is not used.
--   event_seq INTEGER PRIMARY KEY (rowid alias)
--                           -> BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
--       Still ascending in insert order, but a rolled-back insert consumes
--       its value, so the sequence can have gaps (SQLite reuses them).
--   INTEGER -> BIGINT, TEXT -> TEXT COLLATE "C"  (as in aftersales/pg/schema.sql)
--
-- Every timestamp is written by the ActionGateway from the transaction's single
-- business instant (txn_now); nothing here computes a time at load or write time.

-- Stage 6 business extension: SKU variant groups, the only source of exchange
-- compatibility. A SKU without a row is compatible with nothing.
CREATE TABLE sku_variants (
    sku           TEXT COLLATE "C" PRIMARY KEY,
    variant_group TEXT COLLATE "C" NOT NULL,
    updated_at    TEXT COLLATE "C" NOT NULL,
    version       BIGINT NOT NULL CHECK (version >= 1)
);

-- Human handoff tickets: a real persisted record, not a message.
CREATE TABLE human_handoff_tickets (
    ticket_id       TEXT COLLATE "C" PRIMARY KEY,
    order_id        TEXT COLLATE "C" NOT NULL REFERENCES orders (order_id),
    order_item_id   TEXT COLLATE "C" NOT NULL REFERENCES order_items (order_item_id),
    handoff_trigger TEXT COLLATE "C" NOT NULL CHECK (handoff_trigger IN ('quality_dispute')),
    status          TEXT COLLATE "C" NOT NULL CHECK (status IN ('待处理', '处理中', '已关闭')),
    created_at      TEXT COLLATE "C" NOT NULL,
    updated_at      TEXT COLLATE "C" NOT NULL,
    version         BIGINT NOT NULL CHECK (version >= 1)
);

-- Pending actions: everything needed to resume after a restart.
CREATE TABLE pending_actions (
    pending_action_id    TEXT COLLATE "C" PRIMARY KEY,
    idempotency_key      TEXT COLLATE "C" NOT NULL UNIQUE,
    request_id           TEXT COLLATE "C" NOT NULL,
    persona_id           TEXT COLLATE "C" NOT NULL,
    action_name          TEXT COLLATE "C" NOT NULL CHECK (action_name IN
                             ('create_return', 'create_exchange', 'escalate_to_human')),
    args_json            TEXT COLLATE "C" NOT NULL,
    args_sha256          TEXT COLLATE "C" NOT NULL,
    target_order_id      TEXT COLLATE "C" NOT NULL,
    target_order_item_id TEXT COLLATE "C" NOT NULL,
    status               TEXT COLLATE "C" NOT NULL CHECK (status IN ('PENDING_APPROVAL', 'APPROVED',
                             'REJECTED', 'EXECUTED', 'STALE', 'DENIED', 'FAILED')),
    guard_decision       TEXT COLLATE "C" NOT NULL CHECK (guard_decision = 'REQUIRE_APPROVAL'),
    guard_reason_code    TEXT COLLATE "C" NOT NULL,
    snapshot_json        TEXT COLLATE "C" NOT NULL,
    snapshot_sha256      TEXT COLLATE "C" NOT NULL,
    action_spec_version  TEXT COLLATE "C" NOT NULL,
    risk_policy_version  TEXT COLLATE "C" NOT NULL,
    policy_build_id      TEXT COLLATE "C" NOT NULL,
    approval_decision    TEXT COLLATE "C" CHECK (approval_decision IN ('APPROVE', 'REJECT')),
    approver_ref         TEXT COLLATE "C",
    decided_at           TEXT COLLATE "C",
    outcome_code         TEXT COLLATE "C",
    receipt_id           TEXT COLLATE "C" UNIQUE,
    created_at           TEXT COLLATE "C" NOT NULL,
    updated_at           TEXT COLLATE "C" NOT NULL,
    version              BIGINT NOT NULL CHECK (version >= 1),
    CHECK ((approval_decision IS NULL) = (approver_ref IS NULL)),
    CHECK ((approval_decision IS NULL) = (decided_at IS NULL)),
    CHECK (status <> 'PENDING_APPROVAL' OR approval_decision IS NULL),
    CHECK (status NOT IN ('APPROVED', 'EXECUTED', 'STALE', 'DENIED', 'FAILED')
           OR approval_decision IS NOT DISTINCT FROM 'APPROVE'),
    CHECK (status <> 'REJECTED' OR approval_decision IS NOT DISTINCT FROM 'REJECT'),
    CHECK ((status = 'EXECUTED') = (receipt_id IS NOT NULL)),
    CHECK ((status IN ('PENDING_APPROVAL', 'APPROVED', 'EXECUTED')) = (outcome_code IS NULL))
);

-- Execution receipts: exactly one per EXECUTED action, immutable, an idempotency anchor.
CREATE TABLE action_receipts (
    receipt_id          TEXT COLLATE "C" PRIMARY KEY,
    idempotency_key     TEXT COLLATE "C" NOT NULL UNIQUE,
    request_id          TEXT COLLATE "C" NOT NULL,
    persona_id          TEXT COLLATE "C" NOT NULL,
    action_name         TEXT COLLATE "C" NOT NULL CHECK (action_name IN
                            ('create_return', 'create_exchange', 'escalate_to_human')),
    args_json           TEXT COLLATE "C" NOT NULL,
    args_sha256         TEXT COLLATE "C" NOT NULL,
    result_status       TEXT COLLATE "C" NOT NULL CHECK (result_status = 'EXECUTED'),
    resource_type       TEXT COLLATE "C" NOT NULL CHECK (resource_type IN
                            ('after_sales_case', 'human_handoff_ticket')),
    resource_id         TEXT COLLATE "C" NOT NULL,
    pending_action_id   TEXT COLLATE "C" UNIQUE REFERENCES pending_actions (pending_action_id),
    guard_decision      TEXT COLLATE "C" NOT NULL CHECK (guard_decision IN ('ALLOW', 'REQUIRE_APPROVAL')),
    guard_reason_code   TEXT COLLATE "C" NOT NULL,
    snapshot_json       TEXT COLLATE "C" NOT NULL,
    snapshot_sha256     TEXT COLLATE "C" NOT NULL,
    action_spec_version TEXT COLLATE "C" NOT NULL,
    risk_policy_version TEXT COLLATE "C" NOT NULL,
    policy_build_id     TEXT COLLATE "C" NOT NULL,
    executed_at         TEXT COLLATE "C" NOT NULL,
    UNIQUE (resource_type, resource_id),
    CHECK ((action_name = 'escalate_to_human') = (resource_type = 'human_handoff_ticket')),
    CHECK ((guard_decision = 'REQUIRE_APPROVAL') = (pending_action_id IS NOT NULL))
);

-- Append-only audit events (§17); business time; not part of final-state comparison.
CREATE TABLE action_audit_events (
    event_seq         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name        TEXT COLLATE "C" NOT NULL CHECK (event_name IN (
                          'action.replay_hit', 'guard.evaluated', 'guard.failed',
                          'action.pending_created', 'approval.recorded', 'approval.conflict',
                          'resume.started', 'resume.version_check', 'action.executed',
                          'action.not_executed', 'transaction.rolled_back')),
    request_id        TEXT COLLATE "C" NOT NULL,
    persona_id        TEXT COLLATE "C" NOT NULL,
    action_name       TEXT COLLATE "C" NOT NULL,
    idempotency_key   TEXT COLLATE "C",
    pending_action_id TEXT COLLATE "C",
    receipt_id        TEXT COLLATE "C",
    phase             TEXT COLLATE "C" CHECK (phase IN ('start', 'resume')),
    decision          TEXT COLLATE "C",
    code              TEXT COLLATE "C",
    approver_ref      TEXT COLLATE "C",
    at                TEXT COLLATE "C" NOT NULL
);

-- Database-level business invariants: the second line of defence behind the Guard.
CREATE UNIQUE INDEX s6_one_active_case_per_item
    ON after_sales_cases (order_item_id) WHERE status IN ('待处理', '处理中');
CREATE UNIQUE INDEX s6_one_open_pending_per_item
    ON pending_actions (target_order_item_id) WHERE status IN ('PENDING_APPROVAL', 'APPROVED');
CREATE UNIQUE INDEX s6_one_open_ticket_per_item_trigger
    ON human_handoff_tickets (order_item_id, handoff_trigger) WHERE status IN ('待处理', '处理中');
